package JavaTraining;

public class PyramidTriangle {
	
	public static void main(String args[])
	{
		int n=3;
		int rows = 3;
		for(int i=1;i<=rows;i++)
			{
			for(int j=1;j<=i;j++)
					 {
				System.out.print(n+"");
				System.out.print("\t");

				
				n+=3;
			
			         }
			System.out.println(    "");

			
			}
	}

}
